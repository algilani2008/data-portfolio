"""Turn the two GASTAT source tables into a clean long-format CSV and SQL load files.

Inputs  (data/):        total_employed_by_activity.csv, non_saudi_employed_by_activity.csv
Outputs (data/clean/):  employment_by_activity_quarter.csv, activities.csv
        (sql/):         02_data.sql  (INSERT statements for the schema in 01_schema.sql)

Rules applied:
- Q1 2021 is dropped: in the published total table that column duplicates the non-Saudi column.
- Q3 2022 is dropped: not available in the source.
- Only quarters present in both tables are kept (Q2 2021 - Q1 2025).
"""
import csv
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
AR = {
    "Agriculture": "الزراعة والحراجة وصيد الأسماك", "Mining": "التعدين واستغلال المحاجر",
    "Manufacturing": "الصناعات التحويلية", "Electricity": "الكهرباء والغاز والتكييف",
    "Water": "المياه والصرف الصحي وإدارة النفايات", "Construction": "التشييد",
    "Trade": "تجارة الجملة والتجزئة وإصلاح المركبات", "Transport": "النقل والتخزين",
    "Accommodation": "الإقامة وخدمات الطعام", "ICT": "المعلومات والاتصالات",
    "Finance": "الأنشطة المالية والتأمين", "RealEstate": "الأنشطة العقارية",
    "Professional": "الأنشطة المهنية والعلمية والتقنية", "Admin": "الخدمات الإدارية وخدمات الدعم",
    "Public": "الإدارة العامة والدفاع والضمان الاجتماعي", "Education": "التعليم",
    "Health": "الصحة البشرية والعمل الاجتماعي", "Arts": "الفنون والترفيه والتسلية",
    "OtherServices": "أنشطة الخدمات الأخرى", "Households": "الأسر المعيشية بصفتها صاحبة عمل",
    "Extraterritorial": "المنظمات والهيئات الدولية", "NotSpecified": "غير محدد",
}
EN = {
    "Agriculture": "Agriculture, forestry and fishing", "Mining": "Mining and quarrying",
    "Manufacturing": "Manufacturing", "Electricity": "Electricity, gas, steam and air conditioning supply",
    "Water": "Water supply, sewerage and waste management", "Construction": "Construction",
    "Trade": "Wholesale and retail trade; repair of motor vehicles", "Transport": "Transportation and storage",
    "Accommodation": "Accommodation and food service activities", "ICT": "Information and communication",
    "Finance": "Financial and insurance activities", "RealEstate": "Real estate activities",
    "Professional": "Professional, scientific and technical activities",
    "Admin": "Administrative and support service activities",
    "Public": "Public administration and defence; compulsory social security", "Education": "Education",
    "Health": "Human health and social work activities", "Arts": "Arts, entertainment and recreation",
    "OtherServices": "Other service activities", "Households": "Activities of households as employers",
    "Extraterritorial": "Activities of extraterritorial organizations", "NotSpecified": "Not specified",
}


def main():
    tt = pd.read_csv(os.path.join(HERE, "data", "total_employed_by_activity.csv"), index_col=0, na_values="NA")
    ns = pd.read_csv(os.path.join(HERE, "data", "non_saudi_employed_by_activity.csv"), index_col=0, na_values="NA")
    quarters = [q for q in tt.columns if q in ns.columns and q not in ("Q1 2021", "Q3 2022")]
    acts = [a for a in tt.index if a != "Total"]

    for q in quarters:  # sanity checks before writing anything
        assert tt.loc[acts, q].sum() == tt.loc["Total", q], f"total table does not add up in {q}"
        assert ns.loc[acts, q].sum() == ns.loc["Total", q], f"non-Saudi table does not add up in {q}"
        assert (tt.loc[acts, q] >= ns.loc[acts, q]).all(), f"non-Saudi exceeds total in {q}"

    clean = os.path.join(HERE, "data", "clean")
    os.makedirs(clean, exist_ok=True)
    acts_rows = [dict(activity_id=i, activity_code=a, name_en=EN[a], name_ar=AR[a]) for i, a in enumerate(acts, 1)]
    with open(os.path.join(clean, "activities.csv"), "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=list(acts_rows[0]))
        w.writeheader()
        w.writerows(acts_rows)

    rows = []
    for i, a in enumerate(acts, 1):
        for q in quarters:
            total, non = int(tt.loc[a, q]), int(ns.loc[a, q])
            rows.append(dict(activity_id=i, activity_code=a, activity_ar=AR[a], year=int(q[3:]), quarter=int(q[1]),
                             total_employed=total, non_saudi_employed=non, saudi_employed=total - non,
                             saudization_rate=round((total - non) / total, 6) if total else 0))
    with open(os.path.join(clean, "employment_by_activity_quarter.csv"), "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    def lit(s):
        return "'" + str(s).replace("'", "''") + "'"

    sql = ["-- Generated by prepare_data.py from the GASTAT source tables in data/. Run after 01_schema.sql.",
           "BEGIN;"]
    for r in acts_rows:
        sql.append(f"INSERT INTO activities (activity_id, activity_code, name_en, name_ar) VALUES "
                   f"({r['activity_id']}, {lit(r['activity_code'])}, {lit(r['name_en'])}, {lit(r['name_ar'])});")
    for r in rows:
        sql.append(f"INSERT INTO employment (activity_id, year, quarter, total_employed, non_saudi_employed) VALUES "
                   f"({r['activity_id']}, {r['year']}, {r['quarter']}, {r['total_employed']}, {r['non_saudi_employed']});")
    sql.append("COMMIT;")
    with open(os.path.join(HERE, "sql", "02_data.sql"), "w", encoding="utf-8") as f:
        f.write("\n".join(sql) + "\n")
    print(f"{len(acts_rows)} activities, {len(quarters)} quarters, {len(rows)} rows")


if __name__ == "__main__":
    main()
